"""
train_lstm.py — LSTM Training Script
======================================
Trains the TrafficLSTM on data generated by MockCitySimulator, then
evaluates it on the held-out test set and saves the model artifact.

Usage
-----
    python prediction/train_lstm.py
    python prediction/train_lstm.py --epochs 30 --batch-size 64 --seed 42

Outputs (under outputs/lstm/)
------------------------------
    best_model.pt           — saved model state dict + metadata
    scaler_params.json      — normalisation parameters (currently fixed
                              bounds so the file is for bookkeeping only)
    metrics.json            — final train / val / test metrics
    actual_vs_predicted.png — comparison plot for traffic_density
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path
from typing import Dict, Tuple

# Ensure project root is on path
_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(_ROOT))

import numpy as np
import torch
import torch.nn as nn
from torch.optim import Adam
from torch.optim.lr_scheduler import ReduceLROnPlateau

from prediction.dataset import (
    build_datasets,
    make_dataloader,
    DEFAULT_SEQ_LEN,
    DEFAULT_HORIZON,
    DEFAULT_STEPS,
)
from prediction.lstm_model import TrafficLSTM
from prediction.feature_extractor import FEATURE_DIM, TARGET_DIM, TARGET_NAMES

# ---------------------------------------------------------------------------
# Output directory
# ---------------------------------------------------------------------------
OUTPUT_DIR = _ROOT / "outputs" / "lstm"
MODEL_DIR  = _ROOT / "models"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _set_seed(seed: int) -> None:
    torch.manual_seed(seed)
    np.random.seed(seed)


def _evaluate(
    model: TrafficLSTM,
    loader: "torch.utils.data.DataLoader",
    criterion: nn.Module,
    device: "torch.device",
) -> Tuple[float, Dict[str, float]]:
    """
    Run one evaluation pass.

    Returns
    -------
    loss : float
        Mean criterion loss.
    metrics : dict
        MAE and RMSE per target variable.
    """
    model.eval()
    total_loss = 0.0
    all_preds:  list = []
    all_targets: list = []

    with torch.no_grad():
        for X, y in loader:
            X, y = X.to(device), y.to(device)
            pred = model(X)                  # (batch, horizon, target_dim)
            loss = criterion(pred, y)
            total_loss += loss.item() * len(X)
            all_preds.append(pred.cpu().numpy())
            all_targets.append(y.cpu().numpy())

    n = sum(len(X) for X, _ in loader.dataset)  # type: ignore[arg-type]
    # Safer: count via all_preds
    n_samples = sum(p.shape[0] for p in all_preds)
    mean_loss = total_loss / max(n_samples, 1)

    preds   = np.concatenate(all_preds,   axis=0)  # (N, horizon, target_dim)
    targets = np.concatenate(all_targets, axis=0)

    # MAE and RMSE averaged across horizon, per target variable
    metrics: Dict[str, float] = {}
    for i, name in enumerate(TARGET_NAMES):
        p = preds[..., i]
        t = targets[..., i]
        mae  = float(np.mean(np.abs(p - t)))
        rmse = float(np.sqrt(np.mean((p - t) ** 2)))
        metrics[f"{name}_mae"]  = mae
        metrics[f"{name}_rmse"] = rmse

    return mean_loss, metrics


def _denorm_speed(v: float) -> float:
    return v * 120.0

def _denorm_queue(v: float) -> float:
    return v * 1000.0


# ---------------------------------------------------------------------------
# Plot
# ---------------------------------------------------------------------------

def _save_plot(
    actual: np.ndarray,
    predicted: np.ndarray,
    output_path: Path,
    title: str = "TrafficLSTM — Actual vs Predicted Traffic Density",
) -> None:
    """Save an actual-vs-predicted comparison plot."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("  [plot skipped] matplotlib not installed.")
        return

    fig, axes = plt.subplots(1, 1, figsize=(12, 4))

    # Show first 200 samples, first horizon step, traffic_density (index 0)
    n = min(200, len(actual))
    ax = axes
    ax.plot(actual[:n, 0, 0],    label="Actual",    color="#2196F3", linewidth=1.2)
    ax.plot(predicted[:n, 0, 0], label="Predicted", color="#FF5722",
            linewidth=1.2, linestyle="--", alpha=0.85)
    ax.set_title(title, fontsize=12, fontweight="bold")
    ax.set_xlabel("Sample index")
    ax.set_ylabel("Traffic density (normalised)")
    ax.legend()
    ax.grid(True, alpha=0.3)

    plt.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(str(output_path), dpi=120, bbox_inches="tight")
    plt.close(fig)
    print(f"  Plot saved → {output_path}")


# ---------------------------------------------------------------------------
# Training loop
# ---------------------------------------------------------------------------

def train(
    epochs:             int   = 40,
    batch_size:         int   = 64,
    lr:                 float = 1e-3,
    hidden_size:        int   = 64,
    num_layers:         int   = 2,
    dropout:            float = 0.2,
    seq_len:            int   = DEFAULT_SEQ_LEN,
    horizon:            int   = DEFAULT_HORIZON,
    steps_per_scenario: int   = DEFAULT_STEPS,
    seed:               int   = 42,
    patience:           int   = 8,
    save_dir:           Path  = MODEL_DIR,
    output_dir:         Path  = OUTPUT_DIR,
    verbose:            bool  = True,
) -> Dict:
    """
    Full training pipeline:
      1. Generate data from MockCitySimulator (all 8 scenarios).
      2. Build train / val / test datasets.
      3. Train TrafficLSTM with early stopping.
      4. Evaluate on held-out test set.
      5. Save model, metrics, and plot.

    Returns
    -------
    dict with keys: model_path, metrics, best_val_loss, epochs_trained
    """
    _set_seed(seed)
    device = torch.device("cpu")   # CPU only for laptop compatibility

    save_dir.mkdir(parents=True, exist_ok=True)
    output_dir.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # 1. Data
    # ------------------------------------------------------------------
    if verbose:
        print("[1/5] Generating simulation data ...")
        t0 = time.time()

    datasets = build_datasets(
        steps_per_scenario=steps_per_scenario,
        seq_len=seq_len,
        horizon=horizon,
        seed=seed,
    )
    train_ds = datasets["train"]
    val_ds   = datasets["val"]
    test_ds  = datasets["test"]

    if verbose:
        print(
            f"      train={len(train_ds):,}  val={len(val_ds):,}  "
            f"test={len(test_ds):,}  [{time.time()-t0:.1f}s]"
        )

    train_loader = make_dataloader(train_ds, batch_size=batch_size, shuffle=True)
    val_loader   = make_dataloader(val_ds,   batch_size=batch_size, shuffle=False)
    test_loader  = make_dataloader(test_ds,  batch_size=batch_size, shuffle=False)

    # ------------------------------------------------------------------
    # 2. Model
    # ------------------------------------------------------------------
    model = TrafficLSTM(
        input_size=FEATURE_DIM,
        hidden_size=hidden_size,
        num_layers=num_layers,
        horizon=horizon,
        target_dim=TARGET_DIM,
        dropout=dropout,
    ).to(device)

    if verbose:
        print(f"[2/5] Model: {model}")

    criterion = nn.SmoothL1Loss()
    optimiser = Adam(model.parameters(), lr=lr, weight_decay=1e-5)
    scheduler = ReduceLROnPlateau(optimiser, mode="min", factor=0.5,
                                  patience=4)

    # ------------------------------------------------------------------
    # 3. Training loop with early stopping
    # ------------------------------------------------------------------
    if verbose:
        print(f"[3/5] Training for up to {epochs} epochs "
              f"(early-stop patience={patience}) ...")

    best_val_loss = float("inf")
    patience_counter = 0
    best_state: dict = {}
    history = {"train_loss": [], "val_loss": []}

    header = f"  {'Epoch':>5}  {'Train Loss':>10}  {'Val Loss':>10}  {'LR':>8}"
    sep    = "  " + "-" * (len(header) - 2)

    if verbose:
        print(header)
        print(sep)

    for epoch in range(1, epochs + 1):
        # Train
        model.train()
        epoch_loss = 0.0
        n_batches = 0
        for X, y in train_loader:
            X, y = X.to(device), y.to(device)
            optimiser.zero_grad()
            pred = model(X)
            loss = criterion(pred, y)
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            optimiser.step()
            epoch_loss += loss.item()
            n_batches  += 1

        train_loss = epoch_loss / max(n_batches, 1)

        # Validate
        val_loss, _ = _evaluate(model, val_loader, criterion, device)
        scheduler.step(val_loss)
        history["train_loss"].append(train_loss)
        history["val_loss"].append(val_loss)

        current_lr = optimiser.param_groups[0]["lr"]

        if verbose and (epoch % 5 == 0 or epoch == 1):
            print(
                f"  {epoch:>5}  {train_loss:>10.6f}  {val_loss:>10.6f}"
                f"  {current_lr:>8.2e}"
            )

        # Early stopping
        if val_loss < best_val_loss - 1e-6:
            best_val_loss = val_loss
            patience_counter = 0
            best_state = {k: v.clone() for k, v in model.state_dict().items()}
        else:
            patience_counter += 1
            if patience_counter >= patience:
                if verbose:
                    print(f"\n  [Early stopping at epoch {epoch}]")
                break

    epochs_trained = epoch  # type: ignore[possibly-undefined]

    # Restore best weights
    model.load_state_dict(best_state)

    # ------------------------------------------------------------------
    # 4. Test evaluation
    # ------------------------------------------------------------------
    if verbose:
        print(f"\n[4/5] Evaluating on test set ...")

    test_loss, test_metrics = _evaluate(model, test_loader, criterion, device)

    if verbose:
        print(f"  Test SmoothL1 loss : {test_loss:.6f}")
        for name in TARGET_NAMES:
            mae  = test_metrics[f"{name}_mae"]
            rmse = test_metrics[f"{name}_rmse"]
            # Convert normalised metrics to real units for display
            if name == "average_speed":
                mae  *= 120.0
                rmse *= 120.0
                unit = "km/h"
            elif name == "queue_length":
                mae  *= 1000.0
                rmse *= 1000.0
                unit = "m"
            else:
                unit = "(normalised)"
            print(
                f"  {name:20s}  MAE={mae:.4f} {unit:15s}  "
                f"RMSE={rmse:.4f} {unit}"
            )

    # ------------------------------------------------------------------
    # 5. Save
    # ------------------------------------------------------------------
    if verbose:
        print(f"\n[5/5] Saving artefacts ...")

    model_path = save_dir / "best_lstm_model.pt"
    torch.save(
        {
            "state_dict":   model.state_dict(),
            "model_config": {
                "input_size":  FEATURE_DIM,
                "hidden_size": hidden_size,
                "num_layers":  num_layers,
                "horizon":     horizon,
                "target_dim":  TARGET_DIM,
                "dropout":     dropout,
            },
            "seq_len":      seq_len,
            "train_metrics": history,
            "test_metrics":  test_metrics,
            "best_val_loss": best_val_loss,
            "seed":          seed,
        },
        str(model_path),
    )
    if verbose:
        print(f"  Model  → {model_path}")

    # Scaler params (fixed bounds — saved for downstream consumption)
    scaler_path = save_dir / "scaler_params.json"
    scaler_info = {
        "type":   "fixed_domain_bounds",
        "bounds": {
            "vehicle_count":            500.0,
            "average_speed":            120.0,
            "queue_length":             1000.0,
            "pedestrian_count":         300.0,
            "emergency_vehicle_count":  10.0,
        },
        "targets": TARGET_NAMES,
        "note":    "Targets already in [0,1] from FeatureExtractor.extract_targets()",
    }
    with open(scaler_path, "w") as f:
        json.dump(scaler_info, f, indent=2)
    if verbose:
        print(f"  Scaler → {scaler_path}")

    # Metrics JSON
    all_metrics = {
        "test_loss": test_loss,
        "test":      test_metrics,
        "best_val_loss": best_val_loss,
        "epochs_trained": epochs_trained,
    }
    metrics_path = output_dir / "metrics.json"
    metrics_path.parent.mkdir(parents=True, exist_ok=True)
    with open(metrics_path, "w") as f:
        json.dump(all_metrics, f, indent=2)
    if verbose:
        print(f"  Metrics → {metrics_path}")

    # Plot — collect actual vs predicted from test set
    model.eval()
    all_preds:   list = []
    all_targets: list = []
    with torch.no_grad():
        for X, y in test_loader:
            pred = model(X.to(device)).cpu().numpy()
            all_preds.append(pred)
            all_targets.append(y.numpy())

    preds_arr   = np.concatenate(all_preds,   axis=0)
    targets_arr = np.concatenate(all_targets, axis=0)

    plot_path = output_dir / "actual_vs_predicted.png"
    _save_plot(targets_arr, preds_arr, plot_path)

    return {
        "model_path":     str(model_path),
        "metrics":        all_metrics,
        "best_val_loss":  best_val_loss,
        "epochs_trained": epochs_trained,
    }


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------

def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="CityTwin AI — Train LSTM Traffic Predictor"
    )
    p.add_argument("--epochs",    type=int,   default=40)
    p.add_argument("--batch-size",type=int,   default=64)
    p.add_argument("--lr",        type=float, default=1e-3)
    p.add_argument("--hidden",    type=int,   default=64)
    p.add_argument("--layers",    type=int,   default=2)
    p.add_argument("--seq-len",   type=int,   default=DEFAULT_SEQ_LEN)
    p.add_argument("--horizon",   type=int,   default=DEFAULT_HORIZON)
    p.add_argument("--steps",     type=int,   default=DEFAULT_STEPS,
                   help="Simulation steps per scenario (default 300)")
    p.add_argument("--seed",      type=int,   default=42)
    p.add_argument("--patience",  type=int,   default=8)
    p.add_argument("--quiet",     action="store_true")
    return p.parse_args()


if __name__ == "__main__":
    args = _parse_args()
    result = train(
        epochs=args.epochs,
        batch_size=args.batch_size,
        lr=args.lr,
        hidden_size=args.hidden,
        num_layers=args.layers,
        seq_len=args.seq_len,
        horizon=args.horizon,
        steps_per_scenario=args.steps,
        seed=args.seed,
        patience=args.patience,
        verbose=not args.quiet,
    )
    print(f"\nDone. Model saved to: {result['model_path']}")
